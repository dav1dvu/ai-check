/**
 * Scans text and extracts detected heuristic markers and character-level highlights.
 * Incorporates severity weighting, category tagging, and actionable rewrite suggestions.
 */
export function scanHeuristicMarkers(
  text: string,
  preferredLang: 'vi' | 'en' = 'vi'
): {
  metrics: HeuristicMarkerMetrics;
  segments: HighlightSegment[];
} {
  const detectedMarkers: HeuristicMarkerMetrics['detectedMarkers'] = [];
  const segments: HighlightSegment[] = [];
  let totalWords = 1;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) === 32) totalWords++;
  }

  let totalMarkerWeight = 0;
  const lowerText = text.toLowerCase();

  for (const pattern of AI_MARKER_PATTERNS) {
    // Fast O(N) substring pre-filter before running expensive Unicode lookbehind RegExp
    if (pattern.fastCheck && !pattern.fastCheck.some((kw) => lowerText.includes(kw))) {
      continue;
    }

    let match: RegExpExecArray | null;
    pattern.regex.lastIndex = 0;
    const regex = pattern.regex;
    let patternHits = 0;

    while ((match = regex.exec(text)) !== null) {
      patternHits++;
      totalMarkerWeight += pattern.weight;

      const matchedString = match[0];
      const startOffset = match.index;
      const endOffset = startOffset + matchedString.length;

      // Scientific confidence calibrated by pattern weight (weight 1 -> 0.75, weight 5 -> 0.95)
      const confidence = Math.round((0.70 + pattern.weight * 0.05) * 100) / 100;
      const severity = pattern.weight >= 4 ? 'high' : pattern.weight === 3 ? 'medium' : 'low';
      const reason = preferredLang === 'vi' ? pattern.explanationVi : pattern.explanationEn;
      const suggestion = preferredLang === 'vi' ? pattern.suggestionVi : pattern.suggestionEn;

      segments.push({
        id: `marker-${startOffset}-${endOffset}`,
        startOffset,
        endOffset,
        textSnippet: matchedString,
        type: 'formulaic_marker',
        severity,
        confidence,
        reason,
        suggestion,
      });
    }

    if (patternHits > 0) {
      detectedMarkers.push({
        term: pattern.term,
        count: patternHits,
        category: pattern.category,
        suggestion: preferredLang === 'vi' ? pattern.suggestionVi : pattern.suggestionEn,
      });
    }
  }

  const markerCount = segments.length;
  const markerDensity = Math.round((markerCount / (totalWords / 100)) * 100) / 100;

  return {
    metrics: {
      markerCount,
      markerDensity,
      totalMarkerWeight,
      detectedMarkers,
    },
    segments,
  };
}
